export function detectLocale() {
  try {
    const saved = localStorage.getItem('pixelquota_lang');
    if (saved && strings[saved]) return saved;
  } catch {}
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh-TW' : 'en';
}
